const CATEGORY_ICONS = {
  "Smileys & Emotion": "😀",
  "People & Body": "👋",
  "Animals & Nature": "🐶",
  "Food & Drink": "🍔",
  "Activities": "⚽",
  "Travel & Places": "🚗",
  "Objects": "💡",
  "Symbols": "🔣",
  "Flags": "🏁",
};

const CATEGORIES = Object.keys(EMOJI_DATA);

export default function EmojiPicker({ onSelect, onClose }) {
  const [search, setSearch] = useState("");
  const [activeCategory, setActiveCategory] = useState(CATEGORIES[0]);
  const pickerRef = useRef(null);
  const searchRef = useRef(null);

  useEffect(() => {
    function handleClickOutside(e) {
      if (pickerRef.current && !pickerRef.current.contains(e.target)) {
        onClose();
      }
    }
    function handleEscape(e) {
      if (e.key === "Escape") onClose();
    }
    document.addEventListener("mousedown", handleClickOutside);
    document.addEventListener("keydown", handleEscape);
    return () => {
      document.removeEventListener("mousedown", handleClickOutside);
      document.removeEventListener("keydown", handleEscape);
    };
  }, [onClose]);

  useEffect(() => {
    searchRef.current?.focus();
  }, []);

  const filteredEmojis = useMemo(() => {
    if (!search.trim()) return null;
    const q = search.toLowerCase();
    const results = [];
    for (const cat of CATEGORIES) {
      for (const emoji of EMOJI_DATA[cat]) {
        if (emoji.toLowerCase().includes(q)) {
          results.push(emoji);
        }
      }
    }
    return results;
  }, [search]);

  return (
    <div ref={pickerRef} className="emoji-picker">
      <div className="emoji-picker-search">
        <input
          ref={searchRef}
          type="text"
          placeholder="Search emoji..."
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          className="emoji-picker-search-input"
        />
      </div>

      <div className="emoji-picker-categories">
        {CATEGORIES.map((cat) => (
          <button
            key={cat}
            className={`emoji-cat-btn ${activeCategory === cat && !search ? "active" : ""}`}
            onClick={() => { setActiveCategory(cat); setSearch(""); }}
            title={cat}
            type="button"
          >
            {CATEGORY_ICONS[cat]}
          </button>
        ))}
      </div>

      <div className="emoji-picker-grid">
        {filteredEmojis ? (
          filteredEmojis.length === 0 ? (
            <div className="emoji-picker-empty">No emoji found</div>
          ) : (
            <div className="emoji-grid-items">
              {filteredEmojis.map((emoji, i) => (
                <button
                  key={`${emoji}-${i}`}
                  className="emoji-item"
                  onClick={() => onSelect(emoji)}
                  type="button"
                >
                  {emoji}
                </button>
              ))}
            </div>
          )
        ) : (
          <>
            <div className="emoji-category-label">{activeCategory}</div>
            <div className="emoji-grid-items">
              {EMOJI_DATA[activeCategory]?.map((emoji, i) => (
                <button
                  key={`${emoji}-${i}`}
                  className="emoji-item"
                  onClick={() => onSelect(emoji)}
                  type="button"
                >
                  {emoji}
                </button>
              ))}
            </div>
          </>
        )}
      </div>
    </div>
  );
}
